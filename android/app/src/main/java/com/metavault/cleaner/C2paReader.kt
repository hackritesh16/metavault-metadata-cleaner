package com.metavault.cleaner

/**
 * Reads the readable parts of C2PA "content credentials" (the JUMBF manifest stored in PNG caBX chunks and
 * WebP C2PA chunks): which software created the file, when, whether it is marked as AI-generated, and so on.
 * Binary values (hashes, certificates, signatures, icons) are skipped. Pure Kotlin, no Android dependencies.
 *
 * This only READS. It never validates signatures, so nothing here says the credentials are trustworthy.
 */
object C2paReader {
    private class Blob(val size: Int)
    private class Box(val type: String, val start: Int, val end: Int)

    /** Returns key/value rows such as ("C2PA · c2pa.actions.v2 · actions[0].action", "c2pa.created"). Partial on damaged data. */
    fun fields(data: ByteArray, max: Int = 80): List<Pair<String, String>> {
        val out = ArrayList<Pair<String, String>>()
        try {
            readBoxes(data, 0, data.size, 0, out, max)
        } catch (e: RuntimeException) {
            // Keep whatever was read before the damaged part.
        }
        return out
    }

    /** One-line headline for the list, e.g. "marked as AI-generated by ChatGPT (23654 bytes)". */
    fun summary(fields: List<Pair<String, String>>, size: Int): String {
        val ai = fields.any { it.second.contains("trainedAlgorithmicMedia", ignoreCase = true) }
        val agent = fields.firstOrNull { it.first.endsWith("softwareAgent.name") || it.first.endsWith("software_agent.name") }?.second
        val parts = ArrayList<String>()
        if (ai) parts += "marked as AI-generated"
        if (agent != null) parts += "by $agent"
        return if (parts.isEmpty()) "$size bytes" else parts.joinToString(" ") + " ($size bytes)"
    }

    private fun u(d: ByteArray, i: Int): Int = d[i].toInt() and 0xFF

    private fun be32(d: ByteArray, i: Int): Long =
        (u(d, i).toLong() shl 24) or (u(d, i + 1).toLong() shl 16) or (u(d, i + 2).toLong() shl 8) or u(d, i + 3).toLong()

    /** Reads the box header at [pos]; returns null when there is no complete, in-bounds box. */
    private fun boxAt(d: ByteArray, pos: Int, to: Int): Box? {
        if (pos + 8 > to) return null
        var len = be32(d, pos)
        val type = String(d, pos + 4, 4, Charsets.ISO_8859_1)
        var header = 8
        if (len == 1L) { // 64-bit length follows the type
            if (pos + 16 > to) return null
            len = (be32(d, pos + 8) shl 32) or be32(d, pos + 12)
            header = 16
        } else if (len == 0L) {
            len = (to - pos).toLong()
        }
        if (len < header || len > to - pos) return null
        return Box(type, pos + header, pos + len.toInt())
    }

    private fun readBoxes(d: ByteArray, from: Int, to: Int, depth: Int, out: MutableList<Pair<String, String>>, max: Int) {
        var pos = from
        while (out.size < max) {
            val box = boxAt(d, pos, to) ?: return
            if (box.type == "jumb") superbox(d, box, depth, out, max)
            pos = box.end
        }
    }

    /** A JUMBF superbox: one description box ("jumd", holds the label) followed by content boxes. */
    private fun superbox(d: ByteArray, box: Box, depth: Int, out: MutableList<Pair<String, String>>, max: Int) {
        if (depth > 8) return
        var pos = box.start
        var label = ""
        val desc = boxAt(d, pos, box.end)
        if (desc != null && desc.type == "jumd") {
            label = descriptionLabel(d, desc)
            pos = desc.end
        }
        while (out.size < max) {
            val child = boxAt(d, pos, box.end) ?: return
            when (child.type) {
                "cbor" -> readCbor(d, child, label, out, max)
                "jumb" -> superbox(d, child, depth + 1, out, max)
            }
            pos = child.end
        }
    }

    /** jumd payload: 16-byte type, 1 toggle byte, then (when toggle bit 0x02 is set) a null-terminated label. */
    private fun descriptionLabel(d: ByteArray, desc: Box): String {
        if (desc.end - desc.start < 18) return ""
        val toggles = u(d, desc.start + 16)
        if ((toggles and 0x02) == 0) return ""
        val from = desc.start + 17
        var e = from
        while (e < desc.end && d[e].toInt() != 0) e++
        return String(d, from, e - from, Charsets.UTF_8)
    }

    private fun readCbor(d: ByteArray, box: Box, label: String, out: MutableList<Pair<String, String>>, max: Int) {
        if (label == "c2pa.signature") {
            out += rowKey(label, "") to "present (certificate data not shown)"
            return
        }
        try {
            flatten(label, "", Cbor(d, box.start, box.end).read(0), out, max)
        } catch (e: RuntimeException) {
            out += rowKey(label, "") to "present, but could not be decoded"
        }
    }

    private fun rowKey(label: String, path: String): String =
        "C2PA \u00B7 " + label.ifEmpty { "data" } + (if (path.isNotEmpty()) " \u00B7 $path" else "")

    private fun flatten(label: String, path: String, v: Any?, out: MutableList<Pair<String, String>>, max: Int) {
        if (out.size >= max) return
        when (v) {
            is Map<*, *> -> for ((k, x) in v) flatten(label, if (path.isEmpty()) k.toString() else "$path.$k", x, out, max)
            is List<*> -> v.forEachIndexed { i, x -> flatten(label, "$path[$i]", x, out, max) }
            is String -> out += rowKey(label, path) to v.take(300)
            is Long, is Boolean, is Double -> out += rowKey(label, path) to v.toString()
            is Blob -> out += rowKey(label, path) to ("binary data (" + v.size + " bytes)")
            else -> {} // null values are omitted
        }
    }

    /** Minimal CBOR decoder: maps, arrays, text, integers, booleans and floats. Bounded depth and size. */
    private class Cbor(private val d: ByteArray, private var pos: Int, private val end: Int) {
        private var items = 0

        fun read(depth: Int): Any? {
            if (depth > 12 || ++items > 3000) throw IllegalArgumentException("CBOR too complex")
            if (pos >= end) throw IllegalArgumentException("CBOR truncated")
            val ib = d[pos++].toInt() and 0xFF
            val major = ib shr 5
            val ai = ib and 0x1F
            if (major == 7) return simple(ai)
            val indefinite = ai == 31
            val n: Long = when {
                ai < 24 -> ai.toLong()
                ai == 24 -> uint(1)
                ai == 25 -> uint(2)
                ai == 26 -> uint(4)
                ai == 27 -> uint(8)
                indefinite -> -1L
                else -> throw IllegalArgumentException("Bad CBOR header")
            }
            if (n < 0 && !indefinite) throw IllegalArgumentException("CBOR value too large")
            return when (major) {
                0 -> n
                1 -> -1L - n
                2 -> { take(n); Blob(n.toInt()) }
                3 -> { val s = take(n); String(d, s, n.toInt(), Charsets.UTF_8) }
                4 -> {
                    val list = ArrayList<Any?>()
                    if (indefinite) {
                        while (!atBreak()) list += read(depth + 1)
                        pos++
                    } else {
                        if (n > end - pos) throw IllegalArgumentException("CBOR truncated")
                        repeat(n.toInt()) { list += read(depth + 1) }
                    }
                    list
                }
                5 -> {
                    val map = LinkedHashMap<String, Any?>()
                    if (indefinite) {
                        while (!atBreak()) { val k = read(depth + 1); map[k.toString()] = read(depth + 1) }
                        pos++
                    } else {
                        if (n > end - pos) throw IllegalArgumentException("CBOR truncated")
                        repeat(n.toInt()) { val k = read(depth + 1); map[k.toString()] = read(depth + 1) }
                    }
                    map
                }
                6 -> read(depth + 1) // tag: decode the wrapped value
                else -> throw IllegalArgumentException("Bad CBOR type")
            }
        }

        private fun atBreak(): Boolean = pos < end && (d[pos].toInt() and 0xFF) == 0xFF

        /** Advances past [n] bytes and returns where they start. Rejects negative (indefinite) or oversized lengths. */
        private fun take(n: Long): Int {
            if (n < 0 || n > end - pos) throw IllegalArgumentException("CBOR truncated")
            val start = pos
            pos += n.toInt()
            return start
        }

        private fun uint(size: Int): Long {
            val s = take(size.toLong())
            var v = 0L
            for (i in 0 until size) v = (v shl 8) or (d[s + i].toLong() and 0xFF)
            return v
        }

        private fun simple(ai: Int): Any? = when (ai) {
            20 -> false
            21 -> true
            24 -> { take(1); null }
            25 -> { take(2); null } // half-precision floats are not decoded
            26 -> java.lang.Float.intBitsToFloat(uint(4).toInt()).toDouble()
            27 -> java.lang.Double.longBitsToDouble(uint(8))
            else -> null
        }
    }
}
